"""Educational study-hours -> marks regression demo on a clearly SYNTHETIC dataset."""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split

PROVENANCE = ("SYNTHETIC data generated by src/student_demo.py: hours ~ Uniform(0.5, 9.5); "
              "marks = 35 + 6*hours + Normal(0, 6), clipped to [0, 100]; seed fixed. These are not real student records.")


def make_student_data(n: int = 120, seed: int = 7) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    hours = rng.uniform(0.5, 9.5, n).round(2)
    marks = np.clip(35 + 6 * hours + rng.normal(0, 6, n), 0, 100).round(1)
    return pd.DataFrame({"study_hours": hours, "marks": marks})


@dataclass
class StudentModel:
    model: LinearRegression
    data: pd.DataFrame
    train: pd.DataFrame
    test: pd.DataFrame
    metrics: dict
    hours_range: tuple[float, float]

    def predict(self, hours: float) -> tuple[float, str | None]:
        if not np.isfinite(hours) or hours < 0:
            raise ValueError("Study hours must be a non-negative number.")
        lo, hi = self.hours_range
        warn = None
        if hours < lo or hours > hi:
            warn = (f"{hours} h is outside the data range ({lo:.1f}-{hi:.1f} h); this is extrapolation "
                    "and may be unreliable.")
        return float(self.model.predict(pd.DataFrame({"study_hours": [hours]}))[0]), warn


def fit_student_model(df: pd.DataFrame | None = None, seed: int = 7, test_size: float = 0.25) -> StudentModel:
    df = make_student_data(seed=seed) if df is None else df
    tr, te = train_test_split(df, test_size=test_size, random_state=seed)
    m = LinearRegression().fit(tr[["study_hours"]], tr["marks"])
    pred = m.predict(te[["study_hours"]])
    metrics = {"mae": mean_absolute_error(te.marks, pred),
               "rmse": float(np.sqrt(mean_squared_error(te.marks, pred))),
               "r2": r2_score(te.marks, pred), "n_train": len(tr), "n_test": len(te),
               "slope": float(m.coef_[0]), "intercept": float(m.intercept_)}
    return StudentModel(m, df, tr, te, metrics, (float(df.study_hours.min()), float(df.study_hours.max())))
